"""Rasterize OFL Bebas Neue numerals into fixed native one-bit cells."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
WIDTH,HEIGHT=34,76

def glyph_mask(digit: int) -> Image.Image:
    font=ImageFont.truetype(str(ROOT/'assets/fonts/BebasNeue-Regular.ttf'),140)
    bounds=[font.getbbox(str(i)) for i in range(10)]
    top=min(b[1] for b in bounds);bottom=max(b[3] for b in bounds)
    widest=max(b[2]-b[0] for b in bounds)
    b=bounds[digit];canvas=Image.new('L',(b[2]-b[0],bottom-top))
    ImageDraw.Draw(canvas).text((-b[0],-top),str(digit),font=font,fill=255)
    width=round(canvas.width*WIDTH/widest)
    canvas=canvas.resize((width,HEIGHT),Image.Resampling.LANCZOS)
    cell=Image.new('L',(WIDTH,HEIGHT));cell.paste(canvas,((WIDTH-width)//2,0))
    return cell.point(lambda value:255 if value>=128 else 0).convert('1')

def main() -> None:
    masks=[glyph_mask(digit) for digit in range(10)]
    bounds=[mask.getbbox() for mask in masks]
    rows=['/* Generated by execution/generate_digits.py. Bebas Neue OFL: licenses/. */','#pragma once','#include <stdint.h>',f'#define DIGIT_WIDTH {WIDTH}',f'#define DIGIT_HEIGHT {HEIGHT}',f'static const uint8_t DIGITS[10][{len(masks[0].tobytes())}] = {{']
    rows += ['  {'+','.join(map(str,mask.tobytes()))+'},' for mask in masks]
    rows += ['};','static const uint8_t DIGIT_LEFT[10] = {'+','.join(str(b[0]) for b in bounds)+'};','static const uint8_t DIGIT_RIGHT[10] = {'+','.join(str(b[2]-1) for b in bounds)+'};']
    (ROOT/'watchface/src/c/digits.h').write_text('\n'.join(rows)+'\n')
    print('Generated ten 34 × 76 athletic numeral masks')
if __name__=='__main__':main()
